import { expect, test, type Page } from '@playwright/test'

const BASE = '/api/v1/productos'
const body = (codigo: string) => ({ codigoProducto: codigo, nombreProducto: 'Producto local E2E', tipoProducto: 'Cuenta', tipoCuenta: 'Ahorro', idTipoProducto: 1 })
const api = (page: Page, ruta: string, metodo = 'GET', datos?: unknown) => page.evaluate(async ({ ruta, metodo, datos }) => {
  const response = await fetch(ruta, { method: metodo, headers: { 'Content-Type': 'application/json' }, body: datos == null ? undefined : JSON.stringify(datos) })
  return { status: response.status, data: response.status === 204 ? null : await response.json() }
}, { ruta, metodo, datos })

test.beforeEach(async ({ page }) => { await page.goto('/productos'); await expect(page.getByRole('heading', { name: 'Productos', exact: true })).toBeVisible() })

