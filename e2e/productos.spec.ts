test('listas de seleccion ocultan Borrador y filtran menores y adultos desde la pantalla de apertura', async ({ page }) => {
  const catalogo = await api(page, '/api/v1/catalogos/productos?tipo=Cuenta')
  expect(catalogo.data.some((p: { codigoProducto: string }) => p.codigoProducto === 'BOR001')).toBe(false)
  await page.goto('/cuentas/abrir')
  await page.getByLabel('Identificación del cliente').fill('1000000001')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  const opciones = page.getByRole('radiogroup', { name: 'Producto de cuenta' })
  await expect(opciones).toContainText('Ahorro para menores')
  await expect(opciones).not.toContainText('Ahorro para adultos')
  await expect(opciones).not.toContainText('borrador')
  await page.getByLabel('Identificación del cliente').fill('1000000002')
  await page.getByRole('button', { name: 'Buscar', exact: true }).click()
  await expect(opciones).toContainText('Ahorro para adultos')
  await expect(opciones).not.toContainText('Ahorro para menores')
})
